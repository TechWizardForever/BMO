def _fill(polygons, value: int, mask: bytearray) -> None:
    """Set every one-degree cell inside the outlines (even-odd, so a line in and out leaves it alone)."""
    for row in range(180):
        lat = 89.5 - row
        for outline in polygons:
            crossings = []
            for (x1, y1), (x2, y2) in zip(outline, outline[1:] + outline[:1]):
                if (y1 <= lat < y2) or (y2 <= lat < y1):
                    crossings.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
            crossings.sort()
            for left, right in zip(crossings[0::2], crossings[1::2]):
                for col in range(max(0, int(math.ceil(left + 179.5))), min(359, int(math.floor(right + 179.5))) + 1):
                    mask[row * 360 + col] = value


def land_mask() -> bytearray:
    """One byte a degree: 1 land, 0 sea. Made once."""
    global _mask
    if _mask is None:
        mask = bytearray(360 * 180)
        _fill([outline for _, outline in LAND], 1, mask)
        _fill(list(WATER), 0, mask)
        _mask = mask
    return _mask


def is_land(lat: float, lon: float) -> bool:
    row = min(179, max(0, int(89.999 - lat) if lat < 90 else 0))
    col = int((lon + 180.0) % 360.0) % 360
    return bool(land_mask()[row * 360 + col])


