def _noise(lat, lon, size=7.0):
    """Smooth 0..1 noise over the globe, so deserts, tundra and dry country have ragged edges, not straight ones."""
    def at(a, b):
        return ((int(a) * 73856093) ^ (int(b) * 19349663) & 0xFFFFFFFF) % 1000 / 999.0
    y, x = lat / size, lon / size
    y0, x0 = math.floor(y), math.floor(x)
    fy, fx = y - y0, x - x0
    fy, fx = fy * fy * (3 - 2 * fy), fx * fx * (3 - 2 * fx)
    top = at(y0, x0) * (1 - fx) + at(y0, x0 + 1) * fx
    bottom = at(y0 + 1, x0) * (1 - fx) + at(y0 + 1, x0 + 1) * fx
    return top * (1 - fy) + bottom * fy


def _land_color(lat, lon):
    wobble = (_noise(lat, lon) - 0.5) * 8  # degrees
    if lat < -60 or lat > 72 + wobble or (lat > 60 and -60 < lon < -15):  # Antarctica, the Arctic, Greenland's ice
        return ICE
    for south, north, west, east in _DESERTS:
        if south - wobble <= lat <= north + wobble and west - wobble <= lon <= east + wobble:
            return DESERT
    if abs(lat) > 58 + wobble:
        return TUNDRA
    if abs(lat) < 14 + wobble * 0.5:
        return FOREST
    return DRY if _noise(lat + 31, lon + 17, 5.0) > 0.68 else GRASS


