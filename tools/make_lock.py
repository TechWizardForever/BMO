#!/usr/bin/env python3
"""Write installer/requirements.lock: every package BMO needs, at the version tested here.

Run with BMO's own Python (.venv/bin/python tools/make_lock.py). Starts from requirements.txt and
follows each installed package's declared dependencies; the versions are the ones installed in this
environment, so the lock is exactly what the tests ran against. --check compares instead of writing.
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import sys
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "installer" / "requirements.lock"
TOOLS_LOCK = ROOT / "installer" / "build-tools.lock"
BUILD_TOOLS = ("pip", "setuptools", "wheel")
# Declared but not installed: no Python 3.12 build exists and BMO uses the ONNX models instead.
NOT_INSTALLED = {"tflite-runtime": "openwakeword"}
HEADER = """# Every Python package BMO needs, at the exact version tested (installer plan, milestone I1).
# Generated by tools/make_lock.py from requirements.txt; do not edit by hand.
# install.sh installs build-tools.lock first, then this list with --no-deps: the list is complete,
# so pip resolves nothing.
"""


def closure(top_level: list[str]) -> tuple[dict[str, str], list[str]]:
    found: dict[str, tuple[str, set]] = {}
    missing: list[str] = []

    def walk(text: str, wanted_by: str) -> None:
        req = Requirement(text)
        key = canonicalize_name(req.name)
        try:
            dist = md.distribution(req.name)
        except md.PackageNotFoundError:
            if NOT_INSTALLED.get(key) != canonicalize_name(wanted_by):
                missing.append(f"{req.name} (needed by {wanted_by})")
            return
        extras = set(req.extras)
        before = found.get(key)
        if before is not None and extras <= before[1]:
            return
        found[key] = (f"{dist.metadata['Name']}=={dist.version}", (before[1] if before else set()) | extras)
        for dep in dist.requires or []:
            child = Requirement(dep)
            if child.marker and not any(child.marker.evaluate({"extra": e}) for e in (extras or {""})):
                continue
            walk(dep, key)

    for line in top_level:
        walk(line, "requirements.txt")
    return {key: pin for key, (pin, _) in found.items()}, missing


def render() -> tuple[str, str]:
    lines = [l.split("#")[0].strip() for l in (ROOT / "requirements.txt").read_text().splitlines()]
    pins, missing = closure([l for l in lines if l])
    if missing:
        raise SystemExit("Not installed in this environment: " + ", ".join(missing))
    tools = "".join(f"{name}=={md.version(name)}\n" for name in BUILD_TOOLS)
    return HEADER + "\n".join(sorted(pins.values(), key=str.lower)) + "\n", tools


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the lock is out of date")
    args = parser.parse_args()
    lock, tools = render()
    if args.check:
        same = LOCK.is_file() and LOCK.read_text() == lock and TOOLS_LOCK.is_file() and TOOLS_LOCK.read_text() == tools
        print("The lock files are up to date." if same else "The lock files are out of date.")
        return 0 if same else 1
    LOCK.write_text(lock)
    TOOLS_LOCK.write_text(tools)
    print(f"Wrote {LOCK.name} ({lock.count('==')} packages) and {TOOLS_LOCK.name}.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
